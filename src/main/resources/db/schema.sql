-- CashFlow AI schema (PostgreSQL).
-- Run manually:  psql "$DATABASE_URL" -f src/main/resources/db/schema.sql
-- Safe to re-run: every statement is IF NOT EXISTS.
-- Column names match Spring Boot's default naming (camelCase -> snake_case).

CREATE TABLE IF NOT EXISTS invoice (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number    VARCHAR(255) NOT NULL UNIQUE,
    paypal_invoice_id VARCHAR(255),
    customer_name     VARCHAR(255),
    customer_email    VARCHAR(255),
    amount            NUMERIC(12, 2) NOT NULL,
    currency          VARCHAR(255) DEFAULT 'USD',
    due_date          DATE,
    status            VARCHAR(255) DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT','SENT','OVERDUE','PARTIALLY_PAID','PAID','DISPUTED','CANCELLED')),
    reference         VARCHAR(255),              -- PO number
    portal_token      VARCHAR(255) UNIQUE,       -- Fix & Pay link secret
    paypal_payer_url  VARCHAR(1000),             -- PayPal page where the customer pays
    created_at        TIMESTAMP(6) WITH TIME ZONE,
    updated_at        TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_invoice_paypal_id ON invoice (paypal_invoice_id);
CREATE INDEX IF NOT EXISTS idx_invoice_customer_email ON invoice (customer_email);

CREATE TABLE IF NOT EXISTS payment (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paypal_payment_id   VARCHAR(255) UNIQUE,
    invoice_id          BIGINT REFERENCES invoice (id),   -- NULL = unmatched
    invoice_number_hint VARCHAR(255),
    payer_email         VARCHAR(255),
    amount              NUMERIC(12, 2) NOT NULL,
    currency            VARCHAR(255) DEFAULT 'USD',
    status              VARCHAR(255) DEFAULT 'COMPLETED'
        CHECK (status IN ('COMPLETED','FAILED','REFUNDED')),
    paid_at             TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_payment_invoice_id ON payment (invoice_id);
CREATE INDEX IF NOT EXISTS idx_payment_hint ON payment (invoice_number_hint);

CREATE TABLE IF NOT EXISTS ar_case (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id         BIGINT NOT NULL REFERENCES invoice (id),
    case_type          VARCHAR(255)
        CHECK (case_type IN ('OVERDUE_INVOICE','RECONCILIATION_MISMATCH','PARTIAL_PAYMENT',
                             'BROKEN_PROMISE','CUSTOMER_REQUEST','DISPUTE')),
    status             VARCHAR(255) DEFAULT 'DETECTED'
        CHECK (status IN ('DETECTED','INVESTIGATING','WAITING_APPROVAL','ACTION_EXECUTED',
                          'MONITORING','RESOLVED','ESCALATED')),
    root_cause         VARCHAR(255)
        CHECK (root_cause IN ('MISSING_PO','NO_RESPONSE','PAYMENT_NOT_RECORDED','PARTIAL_PAYMENT',
                              'LONG_OVERDUE','BROKEN_PROMISE','CUSTOMER_CASH_FLOW','DISPUTED',
                              'DISCOUNT_REQUEST','UNKNOWN')),
    confidence         DOUBLE PRECISION,
    recommended_action VARCHAR(255),
    explanation        VARCHAR(4000),
    next_check_at      DATE,
    created_at         TIMESTAMP(6) WITH TIME ZONE,
    resolved_at        TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_ar_case_invoice_id ON ar_case (invoice_id);

CREATE TABLE IF NOT EXISTS agent_action (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id           BIGINT REFERENCES ar_case (id),
    tool_name         VARCHAR(255),
    action_type       VARCHAR(255),
    status            VARCHAR(255)
        CHECK (status IN ('PENDING_APPROVAL','EXECUTED','REJECTED','BLOCKED','FAILED')),
    actor             VARCHAR(255)
        CHECK (actor IN ('AGENT','OWNER','CUSTOMER_PORTAL','CUSTOMER_AGENT','PAYPAL','SYSTEM')),
    tool_input        VARCHAR(4000),
    tool_output       VARCHAR(4000),
    requires_approval BOOLEAN NOT NULL DEFAULT FALSE,
    policy_reason     VARCHAR(255),
    approved_by       VARCHAR(255),
    created_at        TIMESTAMP(6) WITH TIME ZONE,
    executed_at       TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_agent_action_case_id ON agent_action (case_id);

CREATE TABLE IF NOT EXISTS invoice_message (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoice (id),
    author     VARCHAR(255) CHECK (author IN ('CUSTOMER','CUSTOMER_AGENT','AGENT','OWNER')),
    body       VARCHAR(2000),
    created_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_invoice_message_invoice_id ON invoice_message (invoice_id);

CREATE TABLE IF NOT EXISTS payment_promise (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id BIGINT NOT NULL REFERENCES invoice (id),
    amount     NUMERIC(12, 2) NOT NULL,
    due_date   DATE NOT NULL,
    source     VARCHAR(255),
    status     VARCHAR(255) DEFAULT 'PENDING' CHECK (status IN ('PENDING','KEPT','BROKEN')),
    created_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_payment_promise_invoice_id ON payment_promise (invoice_id);

CREATE TABLE IF NOT EXISTS webhook_event (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paypal_event_id VARCHAR(255) NOT NULL UNIQUE,
    event_type      VARCHAR(255),
    resource_id     VARCHAR(255),
    received_at     TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS timeline_override (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind        VARCHAR(255) NOT NULL,
    source_id   BIGINT NOT NULL,
    label       VARCHAR(255),
    event_time  TIME,
    UNIQUE (kind, source_id)
);

CREATE TABLE IF NOT EXISTS autonomy_rule (
    action_type       VARCHAR(255) PRIMARY KEY,
    mode              VARCHAR(255) CHECK (mode IN ('AUTO','APPROVAL')),
    approval_streak   INTEGER NOT NULL DEFAULT 0,
    updated_at        TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS customer_account (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255),
    email      VARCHAR(255) NOT NULL UNIQUE,
    access_key VARCHAR(255) NOT NULL UNIQUE
);
